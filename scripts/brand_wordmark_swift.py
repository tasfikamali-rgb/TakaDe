#!/usr/bin/env python3
"""Generates App/Sources/Components/TakaWordmark.swift from docs/brand/logo-on-light.svg.

The logo is "৳akaDe": path 0 is the split taka sign, path 1 is "akaDe" (outlined Inter
Display). The Swift shape draws "akaDe" normalised to its own bounding box, and the
lockup constants place TakaMark (a unit square, split = 1) beside it exactly as in the SVG.
Run: python3 scripts/brand_wordmark_swift.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SVG = ROOT / "docs/brand/logo-on-light.svg"
OUT = ROOT / "App/Sources/Components/TakaWordmark.swift"

# TakaMark's split = 1 bounds inside its unit square (TakaMarkHalfShape points +- offset).
MARK_UNIT = (0.17539 - 0.05134, 0.11000 - 0.00877, 0.82461 + 0.05134, 0.89000 + 0.00877)


def parse(d):
    tokens = re.findall(r"[A-Za-z]|-?\d*\.?\d+(?:e-?\d+)?", d)
    out, i, cmd = [], 0, None
    sizes = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6, "Q": 4, "Z": 0}
    while i < len(tokens):
        if re.match(r"[A-Za-z]", tokens[i]):
            cmd = tokens[i]
            i += 1
        assert cmd in sizes, f"unsupported command {cmd}"
        n = sizes[cmd]
        out.append((cmd, [float(t) for t in tokens[i:i + n]]))
        i += n
        if cmd == "M":
            cmd = "L"
        if cmd == "Z" and i < len(tokens) and not re.match(r"[A-Za-z]", tokens[i]):
            raise ValueError("numbers after Z")
    return out


def absolute(cmds):
    """Turns H and V into L, keeping every point absolute."""
    res, cx, cy = [], 0.0, 0.0
    for c, a in cmds:
        if c == "H":
            c, a = "L", [a[0], cy]
        elif c == "V":
            c, a = "L", [cx, a[0]]
        if a:
            cx, cy = a[-2], a[-1]
        res.append((c, a))
    return res


def bounds(cmds):
    xs = [a[k] for _, a in cmds for k in range(0, len(a), 2)]
    ys = [a[k + 1] for _, a in cmds for k in range(0, len(a), 2)]
    return min(xs), min(ys), max(xs), max(ys)


def main():
    paths = re.findall(r'd="([^"]+)"', SVG.read_text())
    mark, word = absolute(parse(paths[0])), absolute(parse(paths[1]))
    mx0, my0, mx1, my1 = bounds(mark)
    wx0, wy0, wx1, wy1 = bounds(word)
    ww, wh = wx1 - wx0, wy1 - wy0
    side = (mx1 - mx0) / (MARK_UNIT[2] - MARK_UNIT[0])
    mark_cx = mx0 - MARK_UNIT[0] * side + side / 2
    mark_cy = my0 - MARK_UNIT[1] * side + side / 2
    lx0, ly0, lx1, ly1 = min(mx0, wx0), min(my0, wy0), max(mx1, wx1), max(my1, wy1)
    lw, lh = lx1 - lx0, ly1 - ly0
    lcx, lcy = (lx0 + lx1) / 2, (ly0 + ly1) / 2

    def pt(x, y):
        return f"p({(x - wx0) / ww:.5f}, {(y - wy0) / wh:.5f})"

    lines = []
    for c, a in word:
        if c == "M":
            lines.append(f"        path.move(to: {pt(*a)})")
        elif c == "L":
            lines.append(f"        path.addLine(to: {pt(*a)})")
        elif c == "C":
            lines.append(f"        path.addCurve(to: {pt(a[4], a[5])}, control1: {pt(a[0], a[1])}, control2: {pt(a[2], a[3])})")
        elif c == "Q":
            lines.append(f"        path.addQuadCurve(to: {pt(a[2], a[3])}, control: {pt(a[0], a[1])})")
        elif c == "Z":
            lines.append("        path.closeSubpath()")

    def f(v):
        return f"{v:.5f}"

    swift = f'''import SwiftUI

/// "akaDe" from the logo "৳akaDe" (docs/brand/logo-on-light.svg, outlined Inter Display), and
/// where TakaMark sits beside it. Generated by scripts/brand_wordmark_swift.py; don't edit.
struct TakaWordmarkShape: Shape {{
    /// Width over height of the word's bounding box.
    static let aspectRatio: CGFloat = {f(ww / wh)}

    func path(in rect: CGRect) -> Path {{
        var path = Path()
        func p(_ x: CGFloat, _ y: CGFloat) -> CGPoint {{ CGPoint(x: rect.minX + x * rect.width, y: rect.minY + y * rect.height) }}
{chr(10).join(lines)}
        return path
    }}
}}

/// The logo lockup, in units of the whole lockup's width (the split ৳ through the "e").
enum TakaLockup {{
    /// Lockup height over width.
    static let heightRatio: CGFloat = {f(lh / lw)}
    /// TakaMark's square frame (split = 1): side, and its centre from the lockup's centre.
    static let markSide: CGFloat = {f(side / lw)}
    static let markCenter = CGPoint(x: {f((mark_cx - lcx) / lw)}, y: {f((mark_cy - lcy) / lw)})
    /// The word's frame: width, and its centre from the lockup's centre.
    static let wordWidth: CGFloat = {f(ww / lw)}
    static let wordCenter = CGPoint(x: {f(((wx0 + wx1) / 2 - lcx) / lw)}, y: {f(((wy0 + wy1) / 2 - lcy) / lw)})
}}
'''
    OUT.write_text(swift)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

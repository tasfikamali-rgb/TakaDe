#!/usr/bin/env python3
"""Refresh the disposable email domain list used to block throwaway sign-ups.

Source: the community-maintained list at
https://github.com/disposable-email-domains/disposable-email-domains, published on PyPI as
`disposable-email-domains`. The PyPI wheel is downloaded and parsed as text (never imported
or executed).

Writes two files from the same list, so the app and the server always agree:
  Packages/TakaDeKit/Sources/TakaDeCore/Resources/disposable-email-domains.txt
  supabase/seed/disposable_email_domains.sql

Usage: python3 scripts/update-disposable-domains.py
Then commit both files and run the seed SQL on Supabase (see supabase/README.md).
"""
from __future__ import annotations

import io
import json
import re
import sys
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TXT = ROOT / "Packages/TakaDeKit/Sources/TakaDeCore/Resources/disposable-email-domains.txt"
SQL = ROOT / "supabase/seed/disposable_email_domains.sql"

# Never block these, even if a future upstream list adds them by mistake.
# privaterelay.appleid.com is Sign in with Apple's "Hide My Email": a real, permanent inbox.
ALLOW = {
    "privaterelay.appleid.com",
    "gmail.com", "googlemail.com", "outlook.com", "hotmail.com", "live.com", "msn.com",
    "yahoo.com", "icloud.com", "me.com", "mac.com", "proton.me", "protonmail.com",
}

DOMAIN = re.compile(r"^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+$")


def fetch_wheel() -> tuple[str, bytes]:
    with urllib.request.urlopen("https://pypi.org/pypi/disposable-email-domains/json", timeout=30) as r:
        meta = json.load(r)
    wheel = next(u for u in meta["urls"] if u["filename"].endswith(".whl"))
    with urllib.request.urlopen(wheel["url"], timeout=60) as r:
        return meta["info"]["version"], r.read()


def parse(wheel: bytes) -> list[str]:
    with zipfile.ZipFile(io.BytesIO(wheel)) as z:
        source = z.read("disposable_email_domains/__init__.py").decode()
    block = source.split("blocklist = {", 1)[1].split("}", 1)[0]
    domains = {d.strip().lower() for d in re.findall(r"'([^']+)'", block)}
    return sorted(d for d in domains if DOMAIN.match(d) and d not in ALLOW)


def main() -> int:
    version, wheel = fetch_wheel()
    domains = parse(wheel)
    if len(domains) < 1000:
        print(f"Only {len(domains)} domains parsed; refusing to overwrite.", file=sys.stderr)
        return 1

    TXT.parent.mkdir(parents=True, exist_ok=True)
    TXT.write_text(
        f"# Disposable email domains, from disposable-email-domains {version} (PyPI).\n"
        "# Generated by scripts/update-disposable-domains.py. Do not edit by hand.\n"
        + "\n".join(domains) + "\n"
    )

    SQL.parent.mkdir(parents=True, exist_ok=True)
    rows = ",\n".join(f"('{d}')" for d in domains)  # DOMAIN regex guarantees no quotes
    SQL.write_text(
        f"-- Disposable email domains, from disposable-email-domains {version} (PyPI).\n"
        "-- Generated by scripts/update-disposable-domains.py. Do not edit by hand.\n"
        "-- Safe to run again: it replaces the whole list.\n"
        "begin;\n"
        "delete from auth_guard.disposable_email_domains;\n"
        "insert into auth_guard.disposable_email_domains (domain) values\n"
        f"{rows};\n"
        "commit;\n"
    )
    print(f"Wrote {len(domains)} domains (upstream version {version}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
